/**
 * Generates supabase/seed.sql from the TypeScript fixtures so demo mode and a
 * seeded database contain identical sample content.
 *   npm run db:seed:generate
 * The seed is for development and preview environments only.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fixtureItems, fixturePlans, fixtureSubjects, fixtureTopics, fixtureVersions } from "../src/lib/data/fixtures";
import { structuredContentSchema } from "../src/lib/content/schema";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (xs: string[]) => `array[${xs.map(q).join(", ")}]::text[]`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = [
  "-- GENERATED by scripts/generate-seed.ts. Do not edit by hand.",
  "-- Development/preview sample data only. Do not load into production.",
  "begin;",
  "",
];

for (const s of fixtureSubjects) {
  lines.push(
    `insert into public.subjects (id, name, slug, description, cover_image, published, sort_order) values (${[s.id, s.name, s.slug, s.description, s.cover_image, s.published, s.sort_order].map(q).join(", ")}) on conflict (id) do nothing;`,
  );
}
for (const t of fixtureTopics) {
  lines.push(
    `insert into public.topics (id, subject_id, name, slug) values (${[t.id, t.subject_id, t.name, t.slug].map(q).join(", ")}) on conflict (id) do nothing;`,
  );
}
lines.push("");
for (const i of fixtureItems) {
  lines.push(
    `insert into public.content_items (id, title, slug, subtitle, description, subject_id, topic_id, content_type, difficulty, price_minor_units, currency, is_free, subscription_eligible, estimated_reading_minutes, byline, learning_objectives, pdf_downloadable, featured) values (${[
      q(i.id), q(i.title), q(i.slug), q(i.subtitle), q(i.description), q(i.subject_id), q(i.topic?.id ?? null),
      q(i.content_type), q(i.difficulty), q(i.price_minor_units), q(i.currency), q(i.is_free), q(i.subscription_eligible),
      q(i.estimated_reading_minutes), q(i.byline), arr(i.learning_objectives),
      // PDFs must be generated and verified before a downloadable item can be published.
      q(false), q(i.featured),
    ].join(", ")}) on conflict (id) do nothing;`,
  );
  for (const tag of i.tags) {
    lines.push(`insert into public.content_tags (content_item_id, tag) values (${q(i.id)}, ${q(tag.toLowerCase())}) on conflict do nothing;`);
  }
}
for (const i of fixtureItems) {
  (i.bundle_item_ids ?? []).forEach((child, n) => {
    lines.push(`insert into public.bundle_items (bundle_id, content_item_id, sort_order) values (${q(i.id)}, ${q(child)}, ${n}) on conflict do nothing;`);
  });
}
lines.push("");
for (const v of fixtureVersions) {
  structuredContentSchema.parse(v.structured_content);
  lines.push(
    `insert into public.content_versions (id, content_item_id, version_number, structured_content, change_summary) values (${q(v.id)}, ${q(v.content_item_id)}, 1, ${json(v.structured_content)}, ${q(v.change_summary)}) on conflict (id) do nothing;`,
  );
  lines.push(`update public.content_items set current_version_id = ${q(v.id)}, current_version_number = 1 where id = ${q(v.content_item_id)};`);
}
lines.push("");
for (const i of fixtureItems) {
  lines.push(
    `update public.content_items set publication_status = 'published', published_at = ${q(i.published_at)} where id = ${q(i.id)};`,
  );
}
for (const p of fixturePlans) {
  lines.push(
    `insert into public.plans (id, name, slug, description, price_minor_units, currency, billing_interval, entitlements, active) values (${[q(p.id), q(p.name), q(p.slug), q(p.description), q(p.price_minor_units), q(p.currency), q(p.billing_interval), json(p.entitlements), q(p.active)].join(", ")}) on conflict (id) do nothing;`,
  );
}
lines.push("", "commit;", "");

const out = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}`);
